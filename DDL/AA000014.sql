       CREATEDDATE   TIMESTAMP NOT NULL,
       UPDATEDBY     GRAPHIC(8) NOT NULL,
       UPDATEDDATE   TIMESTAMP NOT NULL,
       CONSTRAINT DEPLOYMENTSKEY
       PRIMARY KEY (DEPLID))
      IN {{DBNAME}}.{{DEPLOYMENTS_TBSNAME}}
      PARTITION BY SIZE
